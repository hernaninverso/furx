    /// US1 exige cobertura TOTAL salvo exclusión explícita y justificada acá.
    /// Hoy: vacío — los 225 comandos están cubiertos.
    const REGISTRY_EXCLUDED: &[&str] = &[];

    /// Extrae los IDs de comando del bloque `generate_handler![...]` de `lib.rs`,
    /// para verificar cobertura sin depender de macros internas de Tauri.
    fn handler_command_ids() -> Vec<String> {
        // Ubica lib.rs relativo a este archivo (src-tauri/src/services/ -> src-tauri/src/lib.rs).
        let lib = include_str!("../lib.rs");
        let start = lib
            .find("generate_handler![")
            .expect("generate_handler! no encontrado en lib.rs");
        let rest = &lib[start..];
        let end = rest
            .find("])")
            .expect("cierre de generate_handler! no encontrado");
        let block = &rest[..end];

        // PASO 1: quitar comentarios `// ...` POR LÍNEA FÍSICA antes de partir por
        // comas. Si se parte por coma primero, un fragmento como
        // `// 014 — best-of-N, pairing-sync, log-history` filtra falsos comandos
        // (pairing-sync, log-history) y además puede tragarse el comando real que
        // está en la línea siguiente del mismo segmento. Limpiar por línea evita ambos.
        let mut cleaned = String::new();
        for physical_line in block.lines() {
            let code = match physical_line.find("//") {
                Some(idx) => &physical_line[..idx],
                None => physical_line,
            };
            cleaned.push_str(code);
            cleaned.push('\n');
        }

        let mut ids = Vec::new();
        for raw in cleaned.split(',') {
            let line = raw.trim();
            if line.is_empty() {
                continue;
            }
            // Toma el último segmento tras `::` => el nombre del comando.
            if let Some(name) = line.rsplit("::").next() {
                let name = name.trim();
                if !name.is_empty() && name != "generate_handler![" {
                    ids.push(name.to_string());
                }
            }
        }
        ids
    }


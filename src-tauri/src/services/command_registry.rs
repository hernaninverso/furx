//! 015 US1 — Command Registry único y tipado.
//!
//! Fuente ÚNICA de verdad para todos los comandos Tauri. Cada entrada describe
//! un comando con metadata mínima estable (core) usada por la futura command
//! palette (US2), botones/menús, shortcuts, el capability/approval gate (US4) y
//! el sistema de permisos.
//!
//! Diseño:
//! - El núcleo es MÍNIMO y tipado: {id, label, description, category, scope,
//!   risk, visibility, shortcut, requires_confirmation, reversible, deeplink}.
//! - `extra: serde_json::Value` queda como bolsa de metadata extensible para
//!   que features futuras agreguen campos SIN romper el core ni esta tabla.
//! - La tabla se deriva (semi-automáticamente) de la lista `generate_handler!`
//!   de `lib.rs`: NO se mantienen 225 entradas a mano de cero — el generador
//!   las pobló con defaults sensatos por patrón de nombre y acá quedan los
//!   overrides explícitos. El test de consistencia (abajo) es el acceptance de
//!   US1: valida campos obligatorios, IDs únicos y cobertura total contra
//!   `generate_handler!`.
//!
//! BYOK (constitución F-I): este registry NO contiene secrets. `Risk::Credential`
//! es SÓLO metadata para que el gate exija aprobación; las keys viven en el
//! Keychain y las resuelve el backend, nunca el front.

use serde::{Deserialize, Serialize};

/// Alcance de un comando: a qué nivel del árbol de UI aplica.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Scope {
    /// Afecta a toda la app (settings, layout, reset, snapshots).
    App,
    /// Afecta a una ventana concreta (multi-window-ready, US6).
    Window,
    /// Afecta a una vista/dominio.
    View,
    /// Afecta a un pane individual (PTY, terminal).
    Pane,
}

/// Clasificación de riesgo. Metadata para el capability/approval gate (US4).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Risk {
    /// Sin efectos peligrosos: se ejecuta directo desde la palette.
    Safe,
    /// Borra/resetea/descarta estado: requiere confirmación, no reversible.
    Destructive,
    /// Toca credenciales/keys/cuentas (BYOK): el gate exige aprobación.
    /// NO implica que el registry tenga el secret — sólo lo marca.
    Credential,
    /// Habla con un servicio externo (red): cloud, gh, telegram, vpn, etc.
    External,
}

/// Dónde se muestra el comando.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Visibility {
    /// Acción de primera clase (botón visible en una superficie).
    Primary,
    /// Aparece en la command palette ⌘K (US2).
    Palette,
    /// Plumbing interno (state/status/pty/boot/health): no se ofrece al usuario.
    Internal,
    /// Existe pero deliberadamente oculto de toda superficie.
    Hidden,
}

/// Definición tipada de un comando. Core mínimo + `extra` extensible.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CommandDef {
    /// Identificador estable = nombre del comando Tauri (snake_case). Único.
    pub id: String,
    /// Etiqueta legible para UI.
    pub label: String,
    /// Descripción corta (puede estar vacía en el baseline auto-derivado).
    pub description: String,
    /// Dominio/categoría para agrupar en nav/palette.
    pub category: String,
    pub scope: Scope,
    pub risk: Risk,
    pub visibility: Visibility,
    /// Shortcut declarativo (no hardcodeado en el front). `None` por defecto.
    pub shortcut: Option<String>,
    /// Si el gate (US4) debe pedir confirmación antes de ejecutar.
    pub requires_confirmation: bool,
    /// Si la acción es reversible (informativo para el gate/undo).
    pub reversible: bool,
    /// Deep-link a UI propia (US9 router: furx://...). `None` por defecto.
    pub deeplink: Option<String>,
    /// Metadata extensible para features futuras. Objeto JSON, default `{}`.
    pub extra: serde_json::Value,
}

/// Helper de construcción usado por la tabla generada. Mantiene la tabla legible
/// (una línea por comando) y aplica los defaults del core (`shortcut=None`,
/// `deeplink=None`, `extra={}`, `description=""`).
#[allow(clippy::too_many_arguments)]
fn e(
    id: &str,
    _qualifier: &str,
    label: &str,
    category: &str,
    scope: Scope,
    risk: Risk,
    visibility: Visibility,
    requires_confirmation: bool,
    reversible: bool,
) -> CommandDef {
    CommandDef {
        id: id.to_string(),
        label: label.to_string(),
        description: String::new(),
        category: category.to_string(),
        scope,
        risk,
        visibility,
        shortcut: None,
        requires_confirmation,
        reversible,
        deeplink: None,
        extra: serde_json::Value::Object(serde_json::Map::new()),
    }
}

/// Igual que `e(...)` pero marca el comando como SÓLO de desarrollo (`extra.dev_only = true`).
///
/// P0b (audit 3-frontera HIGH 2): el front (CommandPalette015) usa este marcador para NO
/// listar el comando en builds de producción (`!import.meta.env.DEV`). El backend ya rechaza
/// estos comandos en release (guard `cfg!(debug_assertions)`), así que esto es defensa en capas:
/// ocultarlo de la palette evita que el usuario lo vea/dispare en prod. El comando sigue en el
/// registry (cobertura 1:1 con `generate_handler!`) — sólo lleva metadata extra.
#[allow(clippy::too_many_arguments)]
fn e_dev(
    id: &str,
    qualifier: &str,
    label: &str,
    category: &str,
    scope: Scope,
    risk: Risk,
    visibility: Visibility,
    requires_confirmation: bool,
    reversible: bool,
) -> CommandDef {
    let mut def = e(
        id,
        qualifier,
        label,
        category,
        scope,
        risk,
        visibility,
        requires_confirmation,
        reversible,
    );
    if let serde_json::Value::Object(map) = &mut def.extra {
        map.insert("dev_only".to_string(), serde_json::Value::Bool(true));
    }
    def
}

